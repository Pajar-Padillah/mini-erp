// Helpers for the generic create / edit dialog of static (mock-data) list pages.
import { reactive } from 'vue'

export type FormRow = Record<string, string | number>

export interface FormColumn {
  prop: string
  label: string
  type?: 'text' | 'date' | 'money' | 'number' | 'percent' | 'status' | 'secondary_status'
}

export interface FormStatusOption {
  label: string
  value: string
}

/** The part of a static / master-data page config the form needs. */
export interface FormPageConfig {
  title: string
  newLabel?: string
  dateProp?: string
  statuses?: FormStatusOption[]
  secondaryStatuses?: FormStatusOption[]
  columns: FormColumn[]
}

/**
 * Rows added / edited in this session, per page ("static:<key>" / "master:<key>").
 * Starts as a copy of the page's mock rows; the data files are never modified.
 */
const sessionRows = reactive<Record<string, FormRow[]>>({})

export function pageRows(scope: string, initial: FormRow[]): FormRow[] {
  return sessionRows[scope] ?? initial
}

/** Mutable copy of a page's rows (created on first change). */
export function editableRows(scope: string, initial: FormRow[]): FormRow[] {
  if (!sessionRows[scope]) sessionRows[scope] = initial.map((r) => ({ ...r }))
  return sessionRows[scope]
}

/** The row identifier column (document number / code / name): the first column. */
export const keyProp = (config: FormPageConfig) => config.columns[0]?.prop ?? 'no'

/** Document numbers ("no" columns) are generated by the system; codes and names are typed in. */
export const isAutoNumbered = (config: FormPageConfig) => keyProp(config) === 'no'

/** "+ New Purchase Order" → "Purchase Order"; falls back to the singular page title. */
export function singularName(config: FormPageConfig): string {
  const fromLabel = config.newLabel?.replace(/^\+?\s*New\s+/i, '').trim()
  return fromLabel || config.title.replace(/ies$/, 'y').replace(/s$/, '')
}

/**
 * Next number following the existing pattern: take the value with the highest trailing
 * number and increment it, keeping its prefix and zero padding (PO/2026/10/0010 → PO/2026/10/0011).
 */
export function nextNumber(values: string[], fallbackPrefix = 'DOC'): string {
  let best: { prefix: string; num: number; width: number } | null = null
  for (const value of values) {
    const m = /^(.*?)(\d+)(\D*)$/.exec(value)
    if (!m || m[3]) continue
    const num = Number(m[2])
    if (!best || num > best.num) best = { prefix: m[1], num, width: m[2].length }
  }
  if (!best) return `${fallbackPrefix}-${String(values.length + 1).padStart(4, '0')}`
  return `${best.prefix}${String(best.num + 1).padStart(best.width, '0')}`
}

const DATE_RE = /^\d{4}-\d{2}-\d{2}$/
export type FieldKind = 'text' | 'date' | 'number' | 'status' | 'secondary_status'

export function fieldKind(config: FormPageConfig, column: FormColumn, sample?: FormRow): FieldKind {
  const t = column.type
  if (t === 'status' || t === 'secondary_status') return t
  if (t === 'money' || t === 'number' || t === 'percent') return 'number'
  if (t === 'date' || column.prop === config.dateProp) return 'date'
  if (sample && DATE_RE.test(String(sample[column.prop] ?? ''))) return 'date'
  return 'text'
}

// Values the system derives (stock availability, differences, sync stats...): shown, not typed.
const COMPUTED_LABEL = /\b(available|difference|variance|last sync|last run|calls mtd|book value|outstanding|remaining)\b/i
export const isComputedColumn = (column: FormColumn) => COMPUTED_LABEL.test(column.label)
